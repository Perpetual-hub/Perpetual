// Writes data/geo/centroids.ts: a representative point (centroid of the largest
// polygon) for each country in the Natural Earth 1:110m outlines (world-atlas,
// public domain). Used to place deals on the globe, which have a country but no site.
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const world = require("world-atlas/countries-110m.json");
const countries = require("i18n-iso-countries");

function ringCentroid(ring) {
  let a = 0, x = 0, y = 0;
  for (let i = 0; i < ring.length - 1; i++) {
    const [x0, y0] = ring[i];
    const [x1, y1] = ring[i + 1];
    const f = x0 * y1 - x1 * y0;
    a += f;
    x += (x0 + x1) * f;
    y += (y0 + y1) * f;
  }
  return a === 0 ? null : { area: Math.abs(a / 2), lng: x / (3 * a), lat: y / (3 * a) };
}

const out = {};
for (const f of feature(world, world.objects.countries).features) {
  const iso2 = countries.numericToAlpha2(String(f.id ?? ""));
  if (!iso2) continue;
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.type === "MultiPolygon" ? f.geometry.coordinates : [];
  let best = null;
  for (const p of polys) {
    const c = ringCentroid(p[0]);
    if (c && (!best || c.area > best.area)) best = c;
  }
  if (best) out[iso2] = [Math.round(best.lng * 100) / 100, Math.round(best.lat * 100) / 100];
}
// Small countries missing from the 1:110m outlines (approximate capital or centre, from public geography).
Object.assign(out, { SG: out.SG ?? [103.82, 1.35], MU: out.MU ?? [57.55, -20.2], BH: out.BH ?? [50.56, 26.07], MT: out.MT ?? [14.41, 35.92] });
writeFileSync(
  new URL("../data/geo/centroids.ts", import.meta.url),
  `// GENERATED by scripts/build-centroids.mjs. [lng, lat] per ISO country code.\nexport const centroids: Record<string, [number, number]> = ${JSON.stringify(out)};\n`,
);
console.log(`${Object.keys(out).length} centroids`);
