// Downloads the US EIA International Energy Outlook (IEO) projections of
// installed renewable capacity, world total, for three published scenarios,
// and writes data/stats/capacity-outlook.ts.
//
//   EIA_API_KEY=... node scripts/fetch-eia-outlook.mjs
//
// Without EIA_API_KEY it uses EIA's rate-limited DEMO_KEY. Values are EIA's
// own projections, stored as published (GW). Perpetual makes no forecasts.
// EIA data is a US government work in the public domain; cite "U.S. Energy
// Information Administration".
import { writeFileSync } from "node:fs";

const KEY = process.env.EIA_API_KEY || "DEMO_KEY";
const EDITION = process.env.IEO_EDITION || "2023";
const REGION = "6-0"; // Total World
const SCENARIOS = [
  { id: "Reference", label: "Reference case" },
  { id: "LowZTC", label: "Low zero-carbon technology cost" },
  { id: "HighZTC", label: "High zero-carbon technology cost" },
];
const SERIES = {
  pgcap_rn_sl_gw: "solar",
  pgcap_rn_wn_gw: "wind",
  pgcap_rn_he_gw: "hydro",
  pgcap_rn_gt_gw: "geothermal",
  pgcap_rn_oth_gw: "other",
  pgcap_rn_tot_gw: "total",
  pgcap_sto_bt_gw: "battery",
};

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function get(params) {
  const u = new URL(`https://api.eia.gov/v2/ieo/${EDITION}/data/`);
  u.searchParams.set("api_key", KEY);
  for (const [k, v] of params) u.searchParams.append(k, v);
  for (let attempt = 0; attempt < 5; attempt++) {
    const r = await fetch(u);
    if (r.status === 429) { await sleep(2000 * 2 ** attempt); continue; }
    if (!r.ok) throw new Error(`EIA HTTP ${r.status}`);
    const j = await r.json();
    if (!j.response?.data) throw new Error(`EIA error: ${JSON.stringify(j).slice(0, 300)}`);
    return j.response.data;
  }
  throw new Error("EIA rate limit: set EIA_API_KEY");
}

const scenarios = [];
for (const s of SCENARIOS) {
  const params = [
    ["frequency", "annual"], ["data[]", "value"], ["facets[tableId][]", "21"],
    ["facets[scenario][]", s.id], ["facets[regionId][]", REGION], ["length", "5000"],
    ...Object.keys(SERIES).map((id) => ["facets[seriesId][]", id]),
  ];
  const data = await get(params);
  const byYear = new Map();
  for (const d of data) {
    const year = Number(d.period);
    if (!byYear.has(year)) byYear.set(year, { year });
    byYear.get(year)[SERIES[d.seriesId]] = Math.round(Number(d.value) * 10) / 10;
  }
  const rows = [...byYear.values()].sort((a, b) => a.year - b.year);
  for (const r of rows) for (const k of Object.values(SERIES)) if (typeof r[k] !== "number") throw new Error(`${s.id} ${r.year}: missing ${k}`);
  scenarios.push({ id: s.id, label: s.label, rows });
  await sleep(1500);
}

const source = {
  title: `International Energy Outlook ${EDITION}, installed generating capacity by region and fuel (Table 21), Total World`,
  publisher: "U.S. Energy Information Administration (EIA)",
  citation: `U.S. Energy Information Administration, International Energy Outlook ${EDITION}`,
  url: "https://www.eia.gov/outlooks/ieo/",
  licence: "Public domain (US government work)",
  published: EDITION,
  retrieved: new Date().toISOString().slice(0, 10),
};

const out = `// GENERATED by scripts/fetch-eia-outlook.mjs. Do not edit by hand.
// Source: ${source.citation}. These are EIA's projections, not Perpetual's.
import type { CapacityOutlook } from "@/lib/types";

export const capacityOutlook: CapacityOutlook = ${JSON.stringify({ unit: "GW", edition: EDITION, source, scenarios }, null, 2)};
`;
writeFileSync(new URL("../data/stats/capacity-outlook.ts", import.meta.url), out);
console.log(`Wrote ${scenarios.length} scenarios, ${scenarios[0].rows[0].year}–${scenarios[0].rows.at(-1).year}.`);
