"""Find a high-resolution, freely licensed landscape photo for every country.

    python3 scripts/fetch-country-photos.py

Starts from each country's Wikivoyage page banner (Wikidata property P948), which
editors choose as a representative landscape. Banners are narrow crops, so where
the banner's description names the original photo and that original is large
(at least 2400 px wide), the original is used instead. Writes
data/geo/country-photos.ts with the image URL (a 1920 px rendition, a size Wikimedia serves), the
photographer, the licence and the Commons page for attribution. Only free
licences (CC BY, CC BY-SA, CC0, public domain) are kept.
Wikimedia asks for gentle traffic: one request at a time, with back-off on 429.
"""
import json
import re
import time
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UA = {"User-Agent": "PerpetualDataBot/0.1 (country photos; low volume)"}
FREE = re.compile(r"^(CC BY(-SA)? [\d.]+|CC0|Public domain|PD)", re.I)


def get(url, tries=7):
    for i in range(tries):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
                return json.load(r)
        except urllib.error.HTTPError as e:
            if e.code in (429, 503) and i < tries - 1:
                time.sleep(5 * 2**i)
                continue
            raise


def banners():
    q = "SELECT ?iso ?img WHERE { ?c wdt:P297 ?iso; wdt:P948 ?img. }"
    d = get("https://query.wikidata.org/sparql?" + urllib.parse.urlencode({"query": q, "format": "json"}))
    out = {}
    for b in d["results"]["bindings"]:
        out.setdefault(b["iso"]["value"], urllib.parse.unquote(b["img"]["value"].rsplit("/", 1)[-1]))
    return out


def clean(html):
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", html or "")).strip()


def info(title):
    d = get(
        "https://commons.wikimedia.org/w/api.php?"
        + urllib.parse.urlencode(
            {
                "action": "query",
                "titles": title,
                "prop": "imageinfo|revisions",
                "iiprop": "size|url|extmetadata",
                "iiurlwidth": "1920",
                "rvprop": "content",
                "rvslots": "main",
                "format": "json",
            }
        )
    )
    time.sleep(1.2)
    p = next(iter(d["query"]["pages"].values()))
    if "imageinfo" not in p:
        return None
    ii = p["imageinfo"][0]
    em = ii.get("extmetadata", {})
    return {
        "file": title[5:],
        "width": ii["width"],
        "height": ii["height"],
        "url": ii.get("thumburl") or ii["url"],
        "page": ii["descriptionurl"],
        "license": clean(em.get("LicenseShortName", {}).get("value")),
        "artist": clean(em.get("Artist", {}).get("value"))[:120],
        "text": p.get("revisions", [{}])[0].get("slots", {}).get("main", {}).get("*", ""),
    }


def main():
    out = {}
    for iso, banner in sorted(banners().items()):
        if len(iso) != 2:
            continue
        try:
            b = info("File:" + banner)
            if not b:
                continue
            chosen = b
            # Look for the full photo the banner was cropped from.
            for src in re.findall(r"(?:File:|Image:)([^|\]\n{}]+\.(?:jpe?g|png|tiff?))", b["text"], re.I)[:3]:
                src = src.strip()
                if src.replace("_", " ") == banner.replace("_", " "):
                    continue
                o = info("File:" + src)
                if o and o["width"] >= 2400 and o["height"] >= 1000 and FREE.match(o["license"] or ""):
                    chosen = o
                    break
            if not FREE.match(chosen["license"] or ""):
                continue
            out[iso] = {k: chosen[k] for k in ("url", "width", "height", "page", "license", "artist")}
            out[iso]["banner"] = chosen is b
            print(iso, chosen["width"], "x", chosen["height"], chosen["license"], "(banner)" if chosen is b else "(original)")
        except Exception as e:  # noqa: BLE001
            print("skip", iso, e)
    (ROOT / "data/geo/country-photos.ts").write_text(
        "// GENERATED by scripts/fetch-country-photos.py. Free-licensed photos from Wikimedia Commons.\n"
        "export interface CountryPhoto {\n  url: string;\n  width: number;\n  height: number;\n  page: string;\n  license: string;\n  artist: string;\n  /** True when only the narrow Wikivoyage banner was available. */\n  banner: boolean;\n}\n\n"
        f"export const countryPhotos: Record<string, CountryPhoto> = {json.dumps(out, indent=1, ensure_ascii=False)};\n"
    )
    print(f"Wrote {len(out)} country photos, {sum(not v['banner'] for v in out.values())} full-size originals.")


if __name__ == "__main__":
    main()
