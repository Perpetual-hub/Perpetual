// Downloads IRENA's global installed renewable capacity by technology, as
// published by Our World in Data, and writes data/stats/global-capacity.ts.
//
//   node scripts/fetch-global-capacity.mjs
//
// The source updates once a year (IRENA Renewable Capacity Statistics), so this
// runs on a schedule, not on every page view. Values are kept exactly as
// published (GW). The only derived series is hydropower excluding pumped
// storage, so the stack adds up to IRENA's "All renewables" total.
import { writeFileSync } from "node:fs";

const SLUG = "installed-global-renewable-energy-capacity-by-technology";
const BASE = `https://ourworldindata.org/grapher/${SLUG}`;
const UA = "PerpetualDataBot/0.1 (open data import)";

const get = async (url) => {
  const r = await fetch(url, { headers: { "User-Agent": UA } });
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return r;
};

const meta = await (await get(`${BASE}.metadata.json`)).json();
const csv = await (await get(`${BASE}.csv?useColumnShortNames=true`)).text();

const [header, ...lines] = csv.trim().split("\n");
if (header !== "entity,year,capacity") throw new Error(`Unexpected CSV header: ${header}`);

const raw = new Map(); // entity -> year -> GW
for (const line of lines) {
  const m = line.match(/^"?(.*?)"?,(\d{4}),([\d.]+)$/);
  if (!m) throw new Error(`Unparseable row: ${line}`);
  const [, entity, year, value] = m;
  if (!raw.has(entity)) raw.set(entity, new Map());
  raw.get(entity).set(Number(year), Number(value));
}

const need = ["Solar (total)", "Wind (total)", "Hydropower (total)", "Pumped storage", "Bioenergy (total)", "Geothermal", "Marine", "All renewables (total)"];
for (const n of need) if (!raw.has(n)) throw new Error(`Missing series: ${n}`);

const years = [...raw.get("All renewables (total)").keys()].sort((a, b) => a - b);
const v = (e, y) => raw.get(e).get(y) ?? 0;
const r2 = (x) => Math.round(x * 100) / 100;

const rows = years.map((year) => ({
  year,
  solar: r2(v("Solar (total)", year)),
  wind: r2(v("Wind (total)", year)),
  hydro: r2(v("Hydropower (total)", year) - v("Pumped storage", year)),
  bioenergy: r2(v("Bioenergy (total)", year)),
  geothermal: r2(v("Geothermal", year)),
  marine: r2(v("Marine", year)),
  total: r2(v("All renewables (total)", year)),
}));

const col = Object.values(meta.columns)[0];
const source = {
  title: meta.chart.title,
  publisher: "IRENA, Renewable Energy Statistics",
  via: "Our World in Data",
  citation: col.citationShort,
  url: meta.chart.originalChartUrl,
  licence: "© IRENA. Processing by Our World in Data under CC BY 4.0",
  lastUpdated: col.lastUpdated,
  nextUpdate: col.nextUpdate,
  retrieved: new Date().toISOString().slice(0, 10),
};

const out = `// GENERATED by scripts/fetch-global-capacity.mjs. Do not edit by hand.
// Source: ${source.citation}. ${source.url}
import type { CapacitySeries } from "@/lib/types";

export const globalCapacity: CapacitySeries = ${JSON.stringify({ unit: "GW", source, rows }, null, 2)};
`;
writeFileSync(new URL("../data/stats/global-capacity.ts", import.meta.url), out);
console.log(`Wrote ${rows.length} years (${years[0]}–${years.at(-1)}), source updated ${source.lastUpdated}.`);
