"""Import IRENA Renewable Energy Statistics (country sheet) into data/stats/country-capacity.ts.

    python3 scripts/import-irena-countries.py path/to/IRENA_Statistics_Extract_YYYY.xlsx

Download the extract from IRENA's statistics publication page first. Needs openpyxl.
Values are kept as published (MW, MWh), only summed into technology groups:
solar, wind (onshore, offshore), hydro (renewable hydropower), bioenergy,
geothermal, marine, plus fossil fuels, nuclear and pumped storage for context.
Credit: IRENA, Renewable Energy Statistics. IRENA is the source and copyright holder.
"""
import json, subprocess, sys
from collections import defaultdict
from datetime import date
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parent.parent
xlsx = Path(sys.argv[1])
wb = openpyxl.load_workbook(xlsx, read_only=True)

about = [r[0] for r in wb["About"].iter_rows(values_only=True) if r and r[0]]
citation, url = about[0], about[1]
edition = int(citation.split("(")[1][:4])

# ISO3 -> ISO2 via the i18n-iso-countries package the site already uses.
iso = json.loads(subprocess.check_output(
    ["node", "-e", "const c=require('i18n-iso-countries');console.log(JSON.stringify(c.getAlpha3Codes()))"], cwd=ROOT))

iso["XKX"] = "XK"  # Kosovo: user-assigned code, not in ISO 3166-1

GROUP = {
    "Solar energy": "solar", "Renewable hydropower": "hydro", "Bioenergy": "bioenergy",
    "Geothermal energy": "geothermal", "Marine energy": "marine",
}
cap = defaultdict(lambda: defaultdict(lambda: defaultdict(float)))  # iso2 -> key -> year -> MW
gen = defaultdict(lambda: defaultdict(lambda: defaultdict(float)))  # iso2 -> re|all -> year -> GWh
names, regions, missing = {}, {}, set()
years = set()

for r in wb["Country"].iter_rows(min_row=2, values_only=True):
    region, sub, name, iso3, _m49, flow, re_, group, subtech, tech, _pt, _prod, year, value, unit = r
    if value is None or iso3 not in iso:
        if iso3 and iso3 not in iso:
            missing.add((iso3, name))
        continue
    c = iso[iso3]
    names[c], regions[c] = name, region
    years.add(year)
    if flow == "Electrical Capacity":
        assert unit == "MW", unit
        if re_ == "Total Renewable":
            if group == "Wind energy":
                key = "windOffshore" if subtech.startswith("Offshore") else "windOnshore"
            else:
                key = GROUP[group]
        elif group == "Fossil fuels":
            key = "fossil"
        elif subtech == "Nuclear energy":
            key = "nuclear"
        elif group == "Energy storage":
            key = "pumpedStorage"
        else:
            key = "otherNonRenewable"
        cap[c][key][year] += value
    elif flow == "Electrical Production":
        assert unit == "MWh", unit
        gen[c]["all"][year] += value / 1000
        if re_ == "Total Renewable":
            gen[c]["re"][year] += value / 1000

y0, y1 = min(years), max(years)
span = range(y0, y1 + 1)
KEYS = ["solar", "windOnshore", "windOffshore", "hydro", "bioenergy", "geothermal", "marine",
        "fossil", "nuclear", "pumpedStorage", "otherNonRenewable"]

def series(d):
    return [round(d.get(y, 0.0), 1) for y in span]

def gen_series(d):
    # Years IRENA has not published yet stay null, not zero.
    return [round(d[y], 1) if y in d else None for y in span]

countries = []
for c in sorted(cap):
    capacity = {k: series(cap[c][k]) for k in KEYS if any(cap[c][k].values())}
    countries.append({
        "iso2": c,
        "name": names[c],  # IRENA's short name; the site shows its own display name
        "region": regions[c],
        "capacityMW": capacity,
        "generationGWh": {"renewable": gen_series(gen[c]["re"]), "total": gen_series(gen[c]["all"])},
    })

data = {
    "unit": {"capacity": "MW", "generation": "GWh"},
    "years": [y0, y1],
    "source": {
        "title": f"Renewable Energy Statistics {edition}, country data",
        "publisher": "International Renewable Energy Agency (IRENA)",
        "citation": citation,
        "url": url,
        "licence": f"© IRENA {edition}. Reproduced with acknowledgement of IRENA as the source and copyright holder",
        "published": str(edition),
        "retrieved": date.today().isoformat(),
    },
    "countries": countries,
}
out = ROOT / "data/stats/country-capacity.ts"
out.write_text(
    "// GENERATED by scripts/import-irena-countries.py. Do not edit by hand.\n"
    f"// Source: {citation} {url}\n"
    'import type { CountryCapacityData } from "@/lib/types";\n\n'
    f"export const countryCapacity: CountryCapacityData = {json.dumps(data, separators=(',', ':'))};\n"
)
print(f"Wrote {len(countries)} countries, {y0}-{y1}, {out.stat().st_size // 1024} KB")
if missing:
    print("Skipped (no ISO2 code):", sorted(missing))
