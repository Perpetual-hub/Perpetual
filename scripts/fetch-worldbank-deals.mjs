// Imports World Bank renewable energy financings as deal records:
// data/deals-worldbank.ts.
//
//   node scripts/fetch-worldbank-deals.mjs
//
// Source: World Bank Projects & Operations API (open data, CC BY 4.0). Keeps
// energy projects approved since 2015 where renewable energy sectors make up
// at least 25% of the project's sector allocation. Every record links to the
// project's official World Bank page. Summaries are written from the
// structured fields, not copied from World Bank text.
import { writeFileSync } from "node:fs";

const UA = "PerpetualDataBot/0.1 (open data import)";
const FROM = "2015-01-01";
const MIN_SHARE = 25;
const FIELDS = [
  "id", "project_name", "countryshortname", "countrycode", "regionname", "boardapprovaldate",
  "totalcommamt", "curr_ibrd_commitment", "curr_ida_commitment", "status", "borrower", "impagency",
  "sector1", "sector2", "sector3", "sector4", "sector5", "lendinginstr", "url",
].join(",");
const TECH = {
  "Renewable Energy Solar": "solar",
  "Renewable Energy Wind": "wind",
  "Renewable Energy Hydro": "hydro",
  "Renewable Energy Geothermal": "geothermal",
  "Renewable Energy Biomass": "bioenergy",
};
const TECH_WORD = { solar: "solar", wind: "wind", hydro: "hydropower", geothermal: "geothermal", bioenergy: "bioenergy" };

const today = new Date().toISOString().slice(0, 10);
const all = [];
for (let os = 0; ; os += 500) {
  const u = `https://search.worldbank.org/api/v2/projects?format=json&rows=500&os=${os}&mjsectorcode_exact=LX&strdate=${FROM}&fl=${FIELDS}`;
  const r = await fetch(u, { headers: { "User-Agent": UA } });
  if (!r.ok) throw new Error(`World Bank API HTTP ${r.status}`);
  const page = Object.values((await r.json()).projects ?? {});
  all.push(...page);
  if (page.length < 500) break;
}

const slugify = (s) =>
  s.toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 80).replace(/-$/, "");
const usd = (s) => Number(String(s ?? "").replace(/,/g, ""));
const money = (n) =>
  n >= 1e9
    ? `US$${(n / 1e9).toLocaleString("en", { maximumFractionDigits: 2 })} billion`
    : `US$${Math.round(n / 1e6).toLocaleString("en")} million`;
const list = (xs) => (xs.length < 2 ? xs.join("") : `${xs.slice(0, -1).join(", ")} and ${xs.at(-1)}`);
const longDate = (d) =>
  new Date(`${d}T00:00:00Z`).toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" });

const deals = [];
for (const p of all) {
  const sectors = [1, 2, 3, 4, 5].map((i) => p[`sector${i}`]).filter((s) => s && typeof s === "object");
  const re = sectors.filter((s) => TECH[s.Name]);
  const share = re.reduce((s, x) => s + Number(x.Percent || 0), 0);
  if (!re.length || share < MIN_SHARE) continue;
  if (!p.boardapprovaldate || !["Active", "Closed"].includes(p.status)) continue;
  const amount = usd(p.totalcommamt);
  const date = p.boardapprovaldate.slice(0, 10);
  const techs = [...new Set(re.sort((a, b) => b.Percent - a.Percent).map((s) => TECH[s.Name]))];
  const countries = (p.countrycode ?? []).filter((c) => /^[A-Z]{2}$/.test(c));
  const place = p.countryshortname || p.regionname;
  const lenders = [];
  if (usd(p.curr_ibrd_commitment) > 0) lenders.push({ name: "World Bank (IBRD)", role: "lender" });
  if (usd(p.curr_ida_commitment) > 0) lenders.push({ name: "World Bank (IDA)", role: "lender" });
  if (!lenders.length) lenders.push({ name: "World Bank", role: "lender" });

  const summary = [
    `The World Bank approved ${amount > 0 ? `${money(amount)} of financing` : "financing"} for this project in ${place} on ${longDate(date)}.`,
    `Renewable energy (${list(techs.map((t) => TECH_WORD[t]))}) makes up ${share}% of the project's sector allocation.`,
    p.borrower
      ? `The borrower is ${p.borrower.trim()}${p.impagency ? `, and the implementing agency is ${p.impagency.trim()}` : ""}.`
      : "",
    `World Bank project status: ${p.status.toLowerCase()}.`,
  ]
    .filter(Boolean)
    .join(" ");

  deals.push({
    id: `wb-${p.id}`,
    slug: `${slugify(p.project_name)}-${p.id.toLowerCase()}`,
    isSample: false,
    date,
    type: "development finance",
    status: "completed",
    title: p.project_name.trim(),
    technologies: techs,
    countries,
    region: p.regionname || "Global",
    buyers: lenders,
    ...(p.borrower ? { sellers: [{ name: p.borrower.trim(), role: "Borrower" }] } : {}),
    ...(amount > 0 ? { value: { amount, currency: "USD", usd: amount, disclosed: true } } : {}),
    summary,
    sources: [
      {
        publisher: "World Bank",
        title: `Projects & Operations: ${p.project_name.trim()} (${p.id})`,
        url: p.url,
        retrievedAt: today,
      },
    ],
  });
}
deals.sort((a, b) => b.date.localeCompare(a.date));

const header = [
  "// GENERATED by scripts/fetch-worldbank-deals.mjs. Do not edit by hand.",
  "// Source: World Bank Projects & Operations API (open data, CC BY 4.0). Real records, not samples.",
  'import type { Deal } from "@/lib/types";',
  "",
].join("\n");
writeFileSync(
  new URL("../data/deals-worldbank.ts", import.meta.url),
  `${header}\nexport const worldBankDeals: Deal[] = ${JSON.stringify(deals, null, 2)};\n`,
);
const n = new Set(deals.flatMap((d) => d.countries)).size;
console.log(`Kept ${deals.length} of ${all.length} energy projects, ${deals.at(-1)?.date} to ${deals[0]?.date}, ${n} countries.`);
